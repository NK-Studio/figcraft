//! The Unity-side scripts an export ships with (C#, generated text; FigCraft doesn't build them):
//! `DesignPanelScaler` makes 1 panel px = 1 design point on every screen, `PanelSafeAreaApplier`
//! keeps the exported panel safe area containers on `Screen.safeArea`. Both sit next to the
//! component that shows the export: a `PanelRenderer` from Unity 6.5 (`UIDocument` is not used
//! there), a `UIDocument` before. Style: every member has its access modifier written out, and
//! the product name appears only in the namespace.

/// `DesignPanelScaler.cs`.
pub const PANEL_SCALE: (&str, &str) = (
    "DesignPanelScaler.cs",
    r#"// Generated by FigCraft (file.exportUitk). 1 panel px = 1 design point: the panel is the design
// frame's size on every screen. Put it next to the PanelRenderer (Unity 6.5+) or UIDocument (before)
// showing the export, and set designWidth to the frame's portrait width in points. It sets the
// PanelSettings asset that component uses.
using UnityEngine;
using UnityEngine.UIElements;

namespace FigCraft
{
#if UNITY_6000_5_OR_NEWER
    [RequireComponent(typeof(PanelRenderer))]
#else
    [RequireComponent(typeof(UIDocument))]
#endif
    public sealed class DesignPanelScaler : MonoBehaviour
    {
        [Tooltip("The design frame's portrait width in points.")]
        [SerializeField]
        private float designWidth = 393f;

        private int _width;
        private int _height;

        public float DesignWidth
        {
            get { return designWidth; }
            set { designWidth = value; _width = 0; }
        }

        private PanelSettings Settings
        {
            get
            {
#if UNITY_6000_5_OR_NEWER
                return GetComponent<PanelRenderer>().panelSettings;
#else
                return GetComponent<UIDocument>().panelSettings;
#endif
            }
        }

        private void Update()
        {
            if (Screen.width == _width && Screen.height == _height)
            {
                return;
            }
            PanelSettings settings = Settings;
            if (settings == null || designWidth <= 0f)
            {
                return;
            }
            _width = Screen.width;
            _height = Screen.height;
            settings.scaleMode = PanelScaleMode.ConstantPixelSize;
            // The short side is the portrait width in both orientations.
            settings.scale = Mathf.Min(Screen.width, Screen.height) / designWidth;
        }
    }
}
"#,
);

/// `PanelSafeAreaApplier.cs`.
pub const SAFE_AREA: (&str, &str) = (
    "PanelSafeAreaApplier.cs",
    r#"// Generated by FigCraft (file.exportUitk). Moves every panel safe area container of an export
// (class "panel-safe-area") onto Screen.safeArea, in panel coordinates, whenever it changes.
// Put it next to the PanelRenderer (Unity 6.5+) or UIDocument (before) showing the export.
using UnityEngine;
using UnityEngine.UIElements;

namespace FigCraft
{
#if UNITY_6000_5_OR_NEWER
    [RequireComponent(typeof(PanelRenderer))]
#else
    [RequireComponent(typeof(UIDocument))]
#endif
    public sealed class PanelSafeAreaApplier : MonoBehaviour
    {
        private const string ContainerClass = "panel-safe-area";

        private VisualElement _root;
        private Rect _safeArea;
        private Vector2Int _screen;
        private float _panelWidth;

#if UNITY_6000_5_OR_NEWER
        // A PanelRenderer hands over its root whenever it (re)builds the UI (6.6 adds a version).
        private void OnEnable()
        {
            GetComponent<PanelRenderer>().RegisterUIReloadCallback(OnUIReload);
        }

        private void OnDisable()
        {
            GetComponent<PanelRenderer>().UnregisterUIReloadCallback(OnUIReload);
        }

#if UNITY_6000_6_OR_NEWER
        private void OnUIReload(PanelRenderer panelRenderer, VisualElement rootElement, int version)
#else
        private void OnUIReload(PanelRenderer panelRenderer, VisualElement rootElement)
#endif
        {
            _root = rootElement;
            _panelWidth = -1f;
        }
#else
        private void OnEnable()
        {
            _root = GetComponent<UIDocument>().rootVisualElement;
        }
#endif

        private void Update()
        {
#if !UNITY_6000_5_OR_NEWER
            if (_root == null)
            {
                _root = GetComponent<UIDocument>().rootVisualElement;
            }
#endif
            VisualElement root = _root;
            if (root == null || root.panel == null || Screen.width <= 0)
            {
                return;
            }
            float panelWidth = root.panel.visualTree.layout.width;
            if (!(panelWidth > 0f))
            {
                return;
            }
            Rect safeArea = Screen.safeArea;
            Vector2Int screen = new Vector2Int(Screen.width, Screen.height);
            if (safeArea == _safeArea && screen == _screen && Mathf.Approximately(panelWidth, _panelWidth))
            {
                return;
            }
            _safeArea = safeArea;
            _screen = screen;
            _panelWidth = panelWidth;
            // Screen.safeArea counts pixels from the bottom-left; the panel counts from the top-left.
            float k = panelWidth / Screen.width;
            float left = safeArea.xMin * k;
            float right = (Screen.width - safeArea.xMax) * k;
            float top = (Screen.height - safeArea.yMax) * k;
            float bottom = safeArea.yMin * k;
            root.Query(className: ContainerClass).ForEach(container =>
            {
                container.style.left = left;
                container.style.right = right;
                container.style.top = top;
                container.style.bottom = bottom;
            });
        }
    }
}
"#,
);
