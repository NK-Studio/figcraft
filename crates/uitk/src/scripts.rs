//! The Unity-side scripts an export ships with (C#, generated text; FigCraft doesn't build them):
//! `FigcraftPanelScale` makes 1 panel px = 1 design point on every screen, `FigcraftSafeArea`
//! keeps the exported SafeArea containers on `Screen.safeArea`. Both sit next to the component
//! that shows the export: a `PanelRenderer` from Unity 6.5 (`UIDocument` is not used there), a
//! `UIDocument` before.

/// `FigcraftPanelScale.cs`.
pub const PANEL_SCALE: (&str, &str) = (
    "FigcraftPanelScale.cs",
    r#"// Generated by FigCraft (file.exportUitk). 1 panel px = 1 design point: the panel is the FigCraft
// frame's size on every screen. Put it next to the PanelRenderer (Unity 6.5+) or UIDocument (before)
// showing the export, and set designWidth to the frame's portrait width in points. It sets the
// PanelSettings asset that component uses.
using UnityEngine;
using UnityEngine.UIElements;

namespace FigCraft
{
#if UNITY_6000_5_OR_NEWER
    [RequireComponent(typeof(PanelRenderer))]
#else
    [RequireComponent(typeof(UIDocument))]
#endif
    public sealed class FigcraftPanelScale : MonoBehaviour
    {
        [Tooltip("The FigCraft frame's portrait width in points.")]
        public float designWidth = 393f;

        int _width, _height;

        PanelSettings Settings
        {
            get
            {
#if UNITY_6000_5_OR_NEWER
                return GetComponent<PanelRenderer>().panelSettings;
#else
                return GetComponent<UIDocument>().panelSettings;
#endif
            }
        }

        void Update()
        {
            if (Screen.width == _width && Screen.height == _height) return;
            var settings = Settings;
            if (settings == null || designWidth <= 0f) return;
            _width = Screen.width;
            _height = Screen.height;
            settings.scaleMode = PanelScaleMode.ConstantPixelSize;
            // The short side is the portrait width in both orientations.
            settings.scale = Mathf.Min(Screen.width, Screen.height) / designWidth;
        }
    }
}
"#,
);

/// `FigcraftSafeArea.cs`.
pub const SAFE_AREA: (&str, &str) = (
    "FigcraftSafeArea.cs",
    r#"// Generated by FigCraft (file.exportUitk). Moves every SafeArea container of a FigCraft export
// (class "figcraft-safe-area") onto Screen.safeArea, in panel coordinates, whenever it changes.
// Put it next to the PanelRenderer (Unity 6.5+) or UIDocument (before) showing the export.
using UnityEngine;
using UnityEngine.UIElements;

namespace FigCraft
{
#if UNITY_6000_5_OR_NEWER
    [RequireComponent(typeof(PanelRenderer))]
#else
    [RequireComponent(typeof(UIDocument))]
#endif
    public sealed class FigcraftSafeArea : MonoBehaviour
    {
        VisualElement _root;
        Rect _safe;
        Vector2Int _screen;
        float _panelWidth;

#if UNITY_6000_5_OR_NEWER
        // A PanelRenderer hands over its root whenever it (re)builds the UI (6.6 adds a version).
        void OnEnable() => GetComponent<PanelRenderer>().RegisterUIReloadCallback(OnUIReload);
        void OnDisable() => GetComponent<PanelRenderer>().UnregisterUIReloadCallback(OnUIReload);

#if UNITY_6000_6_OR_NEWER
        void OnUIReload(PanelRenderer renderer, VisualElement root, int version)
#else
        void OnUIReload(PanelRenderer renderer, VisualElement root)
#endif
        {
            _root = root;
            _panelWidth = -1f;
        }
#else
        void OnEnable() => _root = GetComponent<UIDocument>().rootVisualElement;
#endif

        void Update()
        {
#if !UNITY_6000_5_OR_NEWER
            if (_root == null) _root = GetComponent<UIDocument>().rootVisualElement;
#endif
            var root = _root;
            if (root == null || root.panel == null || Screen.width <= 0) return;
            float panelWidth = root.panel.visualTree.layout.width;
            if (!(panelWidth > 0f)) return;
            var safe = Screen.safeArea;
            var screen = new Vector2Int(Screen.width, Screen.height);
            if (safe == _safe && screen == _screen && Mathf.Approximately(panelWidth, _panelWidth)) return;
            _safe = safe;
            _screen = screen;
            _panelWidth = panelWidth;
            // Screen.safeArea counts pixels from the bottom-left; the panel counts from the top-left.
            float k = panelWidth / Screen.width;
            float left = safe.xMin * k, right = (Screen.width - safe.xMax) * k;
            float top = (Screen.height - safe.yMax) * k, bottom = safe.yMin * k;
            root.Query(className: "figcraft-safe-area").ForEach(e =>
            {
                e.style.left = left;
                e.style.right = right;
                e.style.top = top;
                e.style.bottom = bottom;
            });
        }
    }
}
"#,
);
